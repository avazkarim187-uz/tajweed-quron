export interface SurahInfo {
  number: number;
  arabicName: string;
  uzbekName: string;
  ayahCount: number;
  page: number;
}

export function getSurahList(): SurahInfo[] {
  const surahMap = new Map<number, SurahInfo>();

  for (const ayah of quranAyahs) {
    if (!surahMap.has(ayah.surahNumber)) {
      surahMap.set(ayah.surahNumber, {
        number: ayah.surahNumber,
        arabicName: ayah.surahName,
        uzbekName: ayah.surahNameUz,
        ayahCount: 0,
        page: ayah.page,
      });
    }
    const info = surahMap.get(ayah.surahNumber)!;
    info.ayahCount += 1;
  }

  return Array.from(surahMap.values());
}
